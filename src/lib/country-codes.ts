/**
 * Expected phone-number digit-length range for a given ISO2 country.
 * India gets an exact, hand-tuned rule (10 digits). Every other country
 * uses a generic reasonable-length fallback (7-15 digits, matching E.164's
 * max national-significant-number length) rather than a hand-tuned rule
 * per country — a deliberate scope decision.
 */
export function phoneDigitRange(iso2: string): { min: number; max: number } {
  if (iso2 === "IN") return { min: 10, max: 10 };
  return { min: 7, max: 15 };
}
